#!/usr/bin/env python3
"""Build content.js for Abigail's past tense course site.

Reads the markdown in ../course/ (and ../README.md for the overview) and emits a
single content.js holding every section as pre-rendered HTML. The site is fully
static: no runtime markdown parsing, no CDN, no build step needed to serve it.

Re-run after editing the markdown:

    cd docs && python3 build.py
"""
import json
import os
import re

import markdown

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# (id, path relative to repo root, nav label, group, emoji, blurb)
SECTIONS = [
    ("overview", "README.md", "Start Here", "Start", "\U0001F570\uFE0F",
     "The five units, the photo-album idea, and your 25-minute plan."),
    ("dashboard", None, "My Stars", "Start", "\U0001F4C8",
     "Your stars and quiz scores - saved in this browser."),
    ("unit-10", "course/01-unit-10.md", "Unit 10: was / were", "The Past Tense", "\U0001F3D6\uFE0F",
     "The past of am / is / are - and how to say no and ask."),
    ("unit-11", "course/02-unit-11.md", "Unit 11: worked / got / went", "The Past Tense", "\u26BD",
     "Past simple: regular -ed verbs and the famous irregulars."),
    ("unit-12", "course/03-unit-12.md", "Unit 12: didn't / Did you…? \u2B50", "The Past Tense", "\u2B50",
     "THE BIG ONE - negatives and questions, with the golden rule."),
    ("unit-13", "course/04-unit-13.md", "Unit 13: I was doing", "The Past Tense", "\U0001F3C3",
     "Past continuous - the video that was playing."),
    ("unit-14", "course/05-unit-14.md", "Unit 14: was doing + did", "The Past Tense", "\U0001F3AC",
     "Putting both past tenses together - while and when."),
    ("did-rules", "course/06-did-rules.md", "The did Rules \u2B50", "Reference", "\U0001F4CB",
     "The Unit 12 cheat sheet - print it."),
    ("irregulars", "course/07-irregular-verbs.md", "Irregular Verbs", "Reference", "\U0001F4D6",
     "The yesterday-forms, in rhyming families."),
    ("grownups", "course/08-grownups.md", "For Parents & Teachers", "Reference", "\U0001F9D1\u200D\U0001F3EB",
     "What each unit teaches and the three errors to watch for."),
]

EXTENSIONS = ["tables", "fenced_code", "sane_lists", "attr_list", "md_in_html"]

GROUP_EMOJI = {"Start": "\U0001F3C1", "The 20 Minutes": "\u23F1\uFE0F", "Reference": "\U0001F5C2\uFE0F"}


def first_heading(text, fallback):
    m = re.search(r"^#\s+(.+)$", text, re.M)
    return m.group(1).strip() if m else fallback


def build():
    quiz_path = os.path.join(ROOT, "course", "quizzes.json")
    quizzes = {}
    if os.path.exists(quiz_path):
        with open(quiz_path, encoding="utf-8") as f:
            quizzes = {k: v for k, v in json.load(f).items() if not k.startswith("_")}

    out = []
    for sid, rel, label, group, emoji, blurb in SECTIONS:
        if rel is None:
            raw, html, kind = "", "", "dashboard"
        else:
            with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
                raw = f.read()
            # The leading H1 becomes the page title, so drop it from the body.
            body = re.sub(r"^#\s+.+\n", "", raw, count=1)
            html, kind = markdown.markdown(body, extensions=EXTENSIONS), "doc"
        out.append({
            "id": sid,
            "label": label,
            "title": first_heading(raw, label),
            "group": group,
            "groupEmoji": GROUP_EMOJI.get(group, "\u2022"),
            "emoji": emoji,
            "blurb": blurb,
            "kind": kind,
            "quiz": quizzes.get(sid),
            "html": html,
        })
    payload = json.dumps({"sections": out}, ensure_ascii=False, separators=(",", ":"))
    js = "/* Generated by build.py - do not edit by hand. */\nwindow.COURSE = " + payload + ";\n"
    dest = os.path.join(HERE, "content.js")
    with open(dest, "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote %s (%s bytes, %d sections)" % (dest, format(len(js), ","), len(out)))


if __name__ == "__main__":
    build()
